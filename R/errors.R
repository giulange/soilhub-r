# Validation errors: `errors` as a data frame, whatever the body shape.

# `detail` is a string, a `{message, errors}` object (publications, source
# ingests) or the list of FastAPI request-validation items `{loc, msg, type}`.
validation_errors_frame <- function(detail) {
  if (is.null(detail)) return(data.frame(message = character()))
  if (is.character(detail)) {
    return(data.frame(message = paste(detail, collapse = " ")))
  }
  items <- NULL
  if (is.list(detail) && !is.null(names(detail)) && "errors" %in% names(detail)) {
    items <- detail$errors
  } else if (is.list(detail) && is.null(names(detail))) {
    items <- detail
  }
  if (length(items) == 0L) {
    return(data.frame(message = detail_message(detail) %||% character()))
  }
  rows <- lapply(items, function(item) {
    if (!is.list(item)) item <- list(message = item)
    lapply(item, function(value) {
      if (is.null(value)) return(NA_character_)
      value <- unlist(value, use.names = FALSE)
      if (length(value) == 1L && is.numeric(value)) return(value)
      paste(value, collapse = ", ")
    })
  })
  columns <- unique(unlist(lapply(rows, names)))
  frame <- lapply(columns, function(column) {
    values <- lapply(rows, function(row) row[[column]] %||% NA)
    unlist(values)
  })
  names(frame) <- columns
  # `loc` of FastAPI items is a path: join it with dots.
  if ("loc" %in% columns) {
    frame$loc <- vapply(
      items,
      function(item) paste(unlist(item$loc), collapse = "."),
      character(1)
    )
  }
  as.data.frame(frame, stringsAsFactors = FALSE)
}

# The human message of an error `detail` (string, object or list).
detail_message <- function(detail) {
  if (is.null(detail)) return(NULL)
  if (is.character(detail)) return(paste(detail, collapse = " "))
  if (is.list(detail) && !is.null(detail$message)) {
    return(as.character(detail$message))
  }
  if (is.list(detail) && is.null(names(detail))) {
    lines <- vapply(detail, function(item) {
      if (!is.list(item)) return(paste(unlist(item), collapse = " "))
      loc <- paste(unlist(item$loc), collapse = ".")
      msg <- item$msg %||% item$message %||% ""
      if (nzchar(loc)) paste0(loc, ": ", msg) else msg
    }, character(1))
    return(paste0("Invalid request: ", paste(lines, collapse = "; ")))
  }
  NULL
}

# First lines of a validation `errors` frame, for the condition message.
errors_summary <- function(errors, max = 5L) {
  if (!is.data.frame(errors) || nrow(errors) == 0L ||
      identical(names(errors), "message")) {
    return("")
  }
  n <- min(nrow(errors), max)
  lines <- vapply(seq_len(n), function(i) {
    row <- errors[i, , drop = FALSE]
    values <- vapply(names(row), function(column) {
      value <- row[[column]]
      if (is.na(value)) return(NA_character_)
      paste0(column, " ", value)
    }, character(1))
    paste0("- ", paste(stats::na.omit(values), collapse = ", "))
  }, character(1))
  if (nrow(errors) > max) {
    lines <- c(lines, sprintf("... and %d more (see `e$errors`)", nrow(errors) - max))
  }
  paste0("\n", paste(lines, collapse = "\n"))
}
