# Load-limit guidance (2.5): the API message, then the equivalent export call.

# Fields of a request body that make up the selection (4.1); the R argument
# names are the API's, so the body selection is the R selection.
selection_fields <- c(
  "datasets", "geometry", "bbox", "country", "variables", "layer", "view",
  "profile_type", "components", "min_cumulative_percent"
)

request_selection <- function(body) {
  if (!is.list(body)) return(NULL)
  keep <- intersect(selection_fields, names(body))
  selection <- body[keep]
  selection[!vapply(selection, is.null, logical(1))]
}

deparse_argument <- function(value) {
  if (inherits(value, "AsIs")) value <- unclass(value)
  if (is.list(value)) value <- unlist(value)
  paste(deparse(value, width.cutoff = 500L), collapse = "")
}

export_hint <- function(selection, format = "gpkg") {
  args <- vapply(
    names(selection),
    function(name) paste0(name, " = ", deparse_argument(selection[[name]])),
    character(1)
  )
  call <- paste0(
    "soil_export(soil, ",
    paste(c(args, sprintf("format = \"%s\"", format)), collapse = ", "),
    ")"
  )
  paste0(
    "To export the same selection: ", call,
    "\nor rerun with too_large = \"export\"."
  )
}

# Build the load-limit condition from the 422 `detail` object. `request` is
# the body sent; `selection` defaults to its selection fields.
load_limit_error <- function(detail, request = NULL, selection = NULL,
                             status = 422L, endpoint = NULL, method = NULL,
                             request_id = NULL, attempts = NULL) {
  selection <- selection %||% request_selection(request)
  channel <- detail$channel %||% NA_character_
  text <- detail$message %||% sprintf(
    "The selection holds more than %s observations, above the limit of the %s channel.",
    format_count(detail$max_observations %||% NA), channel
  )
  if (identical(channel, "sync")) {
    text <- paste0(text, "\n", export_hint(selection))
  }
  soilhub_api_error(
    paste0(text, request_suffix(status, method, endpoint, request_id)),
    status = status, endpoint = endpoint, detail = detail,
    request_id = request_id, code = detail$code %||% "load_limit_exceeded",
    method = method, attempts = attempts,
    channel = channel,
    max_observations = detail$max_observations,
    observation_count = detail$observation_count,
    observation_count_exact = detail$observation_count_exact,
    exports_url = detail$exports_url,
    request = request, selection = selection,
    subclass = "load_limit"
  )
}

request_suffix <- function(status = NULL, method = NULL, endpoint = NULL,
                           request_id = NULL) {
  parts <- character()
  if (!is.null(status)) parts <- c(parts, paste("HTTP", status))
  if (!is.null(endpoint)) {
    parts <- c(parts, paste(c(method, endpoint), collapse = " "))
  }
  if (!is.null(request_id)) parts <- c(parts, paste("request id", request_id))
  if (length(parts) == 0L) return("")
  paste0("\n[", paste(parts, collapse = ", "), "]")
}

