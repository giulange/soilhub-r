#' Errors signalled by soilhub
#'
#' @description
#' Every error raised by the package is a condition of class `soilhub_error`
#' (which inherits from `error` and `condition`) and of one of the classes
#' below, so it can be caught selectively with [tryCatch()] or
#' [withCallingHandlers()]. The fields listed are elements of the condition
#' object (`e$status`, `e$request_id`, ...). They never hold a token or the
#' content of an uploaded file.
#'
#' | Class | Raised when | Fields |
#' | --- | --- | --- |
#' | `soilhub_argument_error` | a bad argument is caught before any request (bbox, enum value, `NA`, `"ALL"`) | `argument` |
#' | `soilhub_dependency_error` | a suggested package (e.g. `sf`) is needed and not installed | `package` |
#' | `soilhub_auth_error` | login denied or timed out, session expired and not renewable, HTTP 401, no default session | `reason` (`login_denied`, `login_timeout`, `session_expired`, `no_refresh_token`, `not_logged_in`, `no_session`), `partial` |
#' | `soilhub_permission_error` | the session lacks the right an operation needs, or HTTP 403 | `required_right`, `rights`, `status`, `endpoint`, `request_id` |
#' | `soilhub_api_error` | any other non-2xx response, an invalid JSON response, retries exhausted | `status`, `endpoint`, `method`, `detail`, `request_id`, `code`, `attempts` |
#' | `soilhub_validation_error` | HTTP 422: the API rejected the request content | as `soilhub_api_error`, plus `errors` (a data frame) |
#' | `soilhub_load_limit_error` | HTTP 422 `load_limit_exceeded`: the selection is above the limit of synchronous requests (or of exports) | as `soilhub_api_error`, plus `channel`, `max_observations`, `observation_count`, `observation_count_exact`, `exports_url`, `request`, `selection` |
#' | `soilhub_not_found_error` | HTTP 404 | as `soilhub_api_error` |
#' | `soilhub_conflict_error` | HTTP 409 (idempotency replay with different content, duplicate product, illegal job transition) | as `soilhub_api_error` |
#' | `soilhub_unavailable_error` | HTTP 503 after the retries, the API cannot be reached, or the request reached the total timeout (not repeated: narrow the selection or export) | as `soilhub_api_error`, `attempts`, `reason` (`timeout`, `transport_error`) |
#' | `soilhub_capability_error` | the server lacks a capability, or its API version is outside the supported range | `capability`, `api_version`, `minimum` |
#' | `soilhub_job_error` | an export or job `failed` or was `cancelled`, polling timed out, or the job id is unknown | `job`, `job_id`, `reason` |
#'
#' `soilhub_validation_error`, `soilhub_load_limit_error`,
#' `soilhub_not_found_error`, `soilhub_conflict_error` and
#' `soilhub_unavailable_error` also inherit from `soilhub_api_error`.
#'
#' A `soilhub_load_limit_error` carries the API's explanation followed by the
#' way out: narrow the selection or request an export of the same selection
#' with `soil_export()`. Its `request` field is the body sent and
#' `selection` the selection arguments, ready to be passed on.
#'
#' When a multi-page read fails after some pages were read, the error carries
#' those pages in `e$partial`: their metadata has `complete = FALSE` and
#' `next_offset`, the offset from which the read can continue.
#'
#' `request_id` is the `X-Request-ID` of the failed request (generated by the
#' client as `soilhub-<yyyymmddHHMMSS>-<8 hex>` and echoed by the API): quote it
#' when reporting a problem.
#'
#' @examples
#' \dontrun{
#' x <- tryCatch(
#'   soil_observations(soil, datasets = "wosis_points"),
#'   soilhub_load_limit_error = function(e) {
#'     message("Selection of ", e$observation_count, " observations: exporting")
#'     NULL
#'   },
#'   soilhub_error = function(e) {
#'     message("Request ", e$request_id, " failed: ", conditionMessage(e))
#'     NULL
#'   }
#' )
#' }
#' @family configuration and errors
#' @name soilhub-errors
#' @aliases soilhub_error soilhub_argument_error soilhub_dependency_error
#'   soilhub_auth_error soilhub_permission_error soilhub_api_error
#'   soilhub_validation_error soilhub_load_limit_error soilhub_not_found_error
#'   soilhub_conflict_error soilhub_unavailable_error soilhub_capability_error
#'   soilhub_job_error
NULL

# ---------------------------------------------------------------------------
# Constructors (internal). Each `soilhub_*_error()` returns the condition;
# `abort()` signals it.

new_soilhub_error <- function(class, message, ..., call = NULL) {
  fields <- list(...)
  structure(
    class = unique(c(class, "soilhub_error", "error", "condition")),
    c(list(message = message, call = call), fields)
  )
}

abort <- function(condition) {
  stop(condition)
}

soilhub_argument_error <- function(message, argument = NULL) {
  new_soilhub_error("soilhub_argument_error", message, argument = argument)
}

soilhub_dependency_error <- function(package, message = NULL) {
  message <- message %||% sprintf(
    "Package '%s' is required for this operation: install.packages(\"%s\").",
    package, package
  )
  new_soilhub_error("soilhub_dependency_error", message, package = package)
}

soilhub_auth_error <- function(message, reason, partial = NULL, ...) {
  new_soilhub_error(
    "soilhub_auth_error", message,
    reason = reason, partial = partial, ...
  )
}

soilhub_permission_error <- function(message, required_right = NULL,
                                     rights = NULL, status = NULL,
                                     endpoint = NULL, request_id = NULL, ...) {
  new_soilhub_error(
    "soilhub_permission_error", message,
    required_right = required_right, rights = rights, status = status,
    endpoint = endpoint, request_id = request_id, ...
  )
}

# `subclass` is one of NULL, "validation", "load_limit", "not_found",
# "conflict", "unavailable".
soilhub_api_error <- function(message, status = NULL, endpoint = NULL,
                              detail = NULL, request_id = NULL, code = NULL,
                              ..., subclass = NULL) {
  class <- "soilhub_api_error"
  if (!is.null(subclass)) {
    class <- c(paste0("soilhub_", subclass, "_error"), class)
  }
  new_soilhub_error(
    class, message,
    status = status, endpoint = endpoint, detail = detail,
    request_id = request_id, code = code, ...
  )
}

soilhub_capability_error <- function(message, capability = NULL,
                                     api_version = NULL, minimum = NULL) {
  new_soilhub_error(
    "soilhub_capability_error", message,
    capability = capability, api_version = api_version, minimum = minimum
  )
}

soilhub_job_error <- function(message, job = NULL, job_id = NULL,
                              reason = NULL) {
  new_soilhub_error(
    "soilhub_job_error", message,
    job = job, job_id = job_id, reason = reason
  )
}

# ---------------------------------------------------------------------------
# Print method: the message, then the safe fields useful in a report.

#' @export
print.soilhub_error <- function(x, ...) {
  cat("<", class(x)[1], ">\n", conditionMessage(x), "\n", sep = "")
  shown <- c(
    "status", "method", "endpoint", "request_id", "code", "attempts",
    "reason", "argument", "package", "required_right", "capability",
    "api_version", "minimum", "job_id", "channel", "max_observations",
    "observation_count"
  )
  for (field in shown) {
    value <- x[[field]]
    if (is.null(value) || length(value) == 0L || is.list(value)) next
    cat(sprintf("  %s: %s\n", field, paste(format(value), collapse = ", ")))
  }
  if (!is.null(x$errors) && is.data.frame(x$errors)) {
    cat(sprintf("  errors: data frame of %d row(s)\n", nrow(x$errors)))
  }
  if (!is.null(x$partial)) {
    # a soilhub_pages, or the soil_table typed from it by a read
    typed <- is.data.frame(x$partial)
    meta <- if (typed) attr(x$partial, "soil_metadata") else x$partial$metadata
    cat(sprintf(
      "  partial: %s row(s) read, next_offset = %s\n",
      format_count(if (typed) nrow(x$partial) else length(x$partial$items)),
      format(meta$next_offset)
    ))
  }
  invisible(x)
}

