# Summaries (WP6, design 4.4, 5.5): soil_summary(), soil_availability(),
# soil_consistency() on the fake API of helper-fake-thematic.R.

server <- fake_thematic_api()

test_that("soil_summary() types the summary of several datasets", {
  soil <- thematic_session(server)
  s <- soil_summary(soil, datasets = c("wise_profiles", "wosis_points"), country = "KEN")
  expect_s3_class(s, "soil_summary")
  expect_identical(s$datasets, c("wise_profiles", "wosis_points"))
  expect_identical(s$geometry, "any")
  expect_identical(s$feature_count, 1520)
  expect_identical(s$horizon_count, 7412)
  expect_identical(s$observation_count, 18734)
  expect_identical(s$observed_feature_count, 1490)
  expect_identical(s$feature_count_by_dataset, c(wise_profiles = 212, wosis_points = 1308))
  expect_identical(s$observation_count_by_dataset, c(wise_profiles = 6021, wosis_points = 12713))
  expect_identical(s$observed_feature_count_by_dataset, c(wise_profiles = 210, wosis_points = 1280))
  expect_identical(s$avg_horizons_per_feature, 4.97)
  expect_identical(s$by_dataset$dataset, c("wise_profiles", "wosis_points"))
  expect_identical(s$by_dataset$horizon_count, c(1104, 6308))
  expect_identical(s$variables, c("CLAY", "ORGC", "PHAQ"))
  expect_identical(s$variables_by_dataset$wise_profiles, c("CLAY", "ORGC"))
  sem <- s$variable_semantics
  expect_s3_class(sem, "data.frame")
  expect_identical(nrow(sem), 5L)
  expect_identical(names(sem)[1:3], c("dataset", "source_code", "canonical_property_key"))
  expect_identical(sem$source_unit[sem$dataset == "wosis_points" & sem$source_code == "CLAY"], "g/100g")
  expect_identical(sem$source_notes[[3]], "per dataset")
  expect_identical(s$formats, c("geojson", "gpkg", "csv", "tsv", "shp"))
  expect_identical(s$warnings, character())
  expect_identical(s$view, "raw")
  expect_null(s$revised)
  # metadata: request, request id, versions, catalog rows for the citations
  meta <- soil_metadata(s)
  expect_identical(meta$endpoint, "/query/summary")
  expect_match(meta$request_ids, request_id_pattern)
  expect_identical(meta$api_version, read_fixture("capabilities.json")$api_version)
  expect_identical(meta$selection, list(datasets = c("wise_profiles", "wosis_points"), country = "KEN"))
  expect_s3_class(meta$datasets, "data.frame")
  expect_identical(meta$datasets$name, c("wise_profiles", "wosis_points"))
  expect_identical(soil_citations(s)$dataset[1], "wise_profiles")
  expect_identical(soil_warnings(s), character())
})

test_that("soil_summary() of one dataset fills the counts by dataset and lists the revised rules", {
  soil <- thematic_session(server)
  s <- soil_summary(soil, datasets = "sotwis_polygons", view = "revised", components = "representative")
  # the API sends null by dataset for a single dataset: the client fills it
  expect_identical(s$feature_count_by_dataset, c(sotwis_polygons = 310))
  expect_identical(s$observation_count_by_dataset, c(sotwis_polygons = 5120))
  expect_identical(s$avg_horizons_per_feature_by_dataset, c(sotwis_polygons = 5))
  expect_identical(s$view, "revised")
  expect_identical(s$components, "representative")
  expect_identical(s$warnings, "Mixed POINT and MULTIPOLYGON geometries")
  rules <- soil_revised_rules(s)
  expect_identical(rules$id, c("R6", "R12", "R12"))
  expect_identical(rules$n[rules$effect %in% "values_hidden"], 2)
  expect_identical(attr(rules, "pairs")$estimate_prid, "TN-AB1")
})

test_that("the print method of soil_summary is a short report", {
  soil <- thematic_session(server)
  s <- soil_summary(soil, datasets = c("wise_profiles", "wosis_points"))
  out <- capture.output(print(s))
  expect_match(out[1], "^# soilhub summary: 1,520 features, 7,412 horizons, 18,734 observations \\| wise_profiles, wosis_points \\| view raw, layer all$")
  expect_true(any(grepl("Counts per dataset", out)))
  expect_true(any(grepl("wosis_points +1,308 +6,308 +12,713", out)))
  expect_true(any(grepl("^Variables \\(3\\): CLAY, ORGC, PHAQ$", out)))
  expect_false(any(grepl("Revised rules", out)))
  capture.output(expect_invisible(print(s)))

  r <- soil_summary(soil, datasets = "sotwis_polygons", view = "revised")
  out <- capture.output(print(r))
  expect_match(out[1], "view revised, layer all$")
  expect_true(any(grepl("^# components: representative$", out)))
  expect_true(any(grepl("Mixed POINT and MULTIPOLYGON geometries", out, fixed = TRUE)))
  expect_true(any(grepl("Revised rules applied", out)))
  expect_true(any(grepl("R12 +values_hidden +2", out)))
})

test_that("summary and availability send the selection of the reads, without layout fields", {
  soil <- thematic_session(server)
  thematic_reset(server)
  args <- list(datasets = "wosis_points", variables = c("ORGC", "CLAY"),
               bbox = c(33, -5, 42, 5), country = "KEN", layer = "first",
               profile_type = c("!synthetic", "!virtual"))
  do.call(soil_summary, c(list(soil), args))
  do.call(soil_availability, c(list(soil), args))
  expected <- do.call(soil_selection, c(list(soil), args))
  attr(expected, "selection") <- NULL
  expected <- jsonlite::fromJSON(request_body_json(expected), simplifyVector = FALSE)
  calls <- thematic_calls(server)
  expect_identical(vapply(calls, `[[`, "", "path"), c("/query/summary", "/query/availability"))
  for (call in calls) {
    expect_identical(call$body, expected)
    expect_false(any(c("layout", "geometry_format", "limit", "offset") %in% names(call$body)))
    expect_identical(call$body$view, "raw")
    expect_true(call$body$canonical)
  }
})

test_that("a bad selection is refused before any request", {
  soil <- thematic_session(server)
  thematic_reset(server)
  expect_error(soil_summary(soil, datasets = "ALL"), class = "soilhub_argument_error")
  expect_error(soil_summary(soil, bbox = c(1, 2, 3)), class = "soilhub_argument_error")
  expect_error(soil_availability(soil, view = "fixed"), class = "soilhub_argument_error")
  expect_error(soil_availability(soil, components = "cumulative"), class = "soilhub_argument_error")
  e <- expect_error(soil_summary(soil, profile_type = c("synthetic", "!virtual")), class = "soilhub_argument_error")
  expect_identical(e$argument, "profile_type")
  expect_length(thematic_calls(server), 0L)
})

test_that("summaries check the optional capabilities of the selection", {
  soil <- thematic_session(server, capabilities_with(revised_view = FALSE, profile_type_filter = FALSE))
  thematic_reset(server)
  e <- expect_error(soil_summary(soil, datasets = "wosis_points", view = "revised"), class = "soilhub_capability_error")
  expect_identical(e$capability, "revised_view")
  expect_match(conditionMessage(e), "soil_summary()", fixed = TRUE)
  e <- expect_error(soil_availability(soil, datasets = "wosis_points", profile_type = "synthetic"), class = "soilhub_capability_error")
  expect_identical(e$capability, "profile_type_filter")
  soil <- thematic_session(server, capabilities_with(component_selection = FALSE))
  expect_error(soil_summary(soil, datasets = "sotwis_polygons", components = "all"), class = "soilhub_capability_error")
  soil <- thematic_session(server, capabilities_with(canonical_summary = FALSE))
  e <- expect_error(soil_availability(soil, datasets = "wosis_points"), class = "soilhub_capability_error")
  expect_identical(e$capability, "canonical_summary")
  expect_length(thematic_calls(server), 0L)
})

test_that("soil_availability() returns typed data frames by dataset, country and variable", {
  soil <- thematic_session(server)
  a <- soil_availability(soil, datasets = c("soter_profiles", "wosis_points"))
  expect_s3_class(a, "soil_availability")
  # dataset totals count a feature once (from the metadata), with the geometry
  expect_identical(a$datasets$dataset, c("soter_profiles", "wosis_points"))
  expect_identical(a$datasets$geometry, c("point", "point"))
  expect_identical(a$datasets$feature_count, c(130, 300))
  expect_identical(a$datasets$observation_count, c(2400, 4000))
  expect_identical(names(a$countries), c("country_code", "country_name", "feature_count", "horizon_count", "observation_count"))
  expect_identical(a$countries$country_code, c("KEN", "TZA"))
  expect_identical(a$countries$feature_count, c(420, 12))
  expect_identical(nrow(a$dataset_countries), 3L)
  expect_false("variables" %in% names(a$dataset_countries))
  v <- a$variables
  expect_identical(nrow(v), 4L)
  expect_identical(names(v)[1:4], c("dataset", "country_code", "country_name", "property_code"))
  expect_type(v$observation_count, "double")
  expect_type(v$variants, "list")
  totc <- v[v$property_code == "TOTC", ]
  expect_s3_class(totc$variants[[1]], "data.frame")
  expect_identical(totc$variants[[1]]$source_scope, "KENSOTER")
  expect_identical(totc$variants[[1]]$source_unit, "%")
  expect_identical(nrow(v$variants[[1]]), 0L)
  expect_identical(soil_metadata(a)$endpoint, "/query/availability")
  expect_identical(soil_citations(a)$dataset[1], "soter_profiles")
  out <- capture.output(print(a))
  expect_match(out[1], "^# soilhub availability: 2 dataset\\(s\\), 2 countries, 4 variable row\\(s\\) \\| view raw$")
})

test_that("soil_consistency() sends its own request and types the calculation it gets", {
  soil <- thematic_session(server)
  thematic_reset(server)
  k <- soil_consistency(soil, datasets = c("soter_profiles", "wosis_points"),
                        geometry = "point", country = "KEN", variables = "clay")
  expect_s3_class(k, "soil_consistency")
  body <- thematic_calls(server, "/query/consistency")[[1]]$body
  expect_identical(body, list(datasets = list("soter_profiles", "wosis_points"),
                              geometry = list("point"), country = list("KEN"),
                              variables = list("clay")))
  # never the fields the endpoint does not take (fact 12.2.7)
  expect_false(any(c("view", "profile_type", "components", "canonical", "layer") %in% names(body)))
  expect_identical(k$metadata$calculation, "live")
  expect_true(is.na(k$metadata$as_of))
  expect_identical(k$totals$feature_count, 430)
  expect_identical(k$totals$value_count, 12)
  expect_identical(k$countries$iso_a3, c("KEN", "TZA"))
  expect_type(k$countries$feature_count, "double")
  expect_identical(k$datasets$dataset_code, c("soter_profiles", "wosis_points"))
  expect_identical(k$variables$observation_count, c(1780, 552))
  expect_match(capture.output(print(k))[1], "^# soilhub consistency \\(live\\): distinct totals, never sum the countries$")

  g <- soil_consistency(soil)
  expect_length(thematic_calls(server, "/query/consistency")[[2]]$body, 0L)
  expect_identical(g$metadata$calculation, "summary")
  expect_identical(g$metadata$summary_scope, "global")
  expect_s3_class(g$metadata$as_of, "POSIXct")
  expect_identical(g$totals$variables, c("clay", "organic_carbon"))
  expect_s3_class(g$datasets$refreshed_at, "POSIXct")
  expect_type(g$datasets$dataset_id, "double")
  expect_identical(nrow(g$countries), 0L)
})

